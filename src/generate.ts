import { randomBytes } from 'node:crypto';
import { join } from 'node:path';

import { defaultPaths, limits, timeZone } from '@tarot/config';
import { type Card, isValidCardName, loadDeck } from '@tarot/deck';
import { GeneratorError } from '@tarot/errors';
import { readTextFile } from '@tarot/files';
import { pickCard, type RandomIndex, secureRandomIndex } from '@tarot/pick';
import { renderTemplate } from '@tarot/template';

export type GenerateOptions = {
  /** The repository root. */
  readonly root: string;
  readonly assetsDir?: string;
  readonly templatePath?: string;
  readonly outputPath?: string;
  readonly now?: Date;
  readonly random?: RandomIndex;
  /** The cache key for the image link. The default is 16 random hexadecimal digits. */
  readonly cacheKey?: string;
};

export type GenerateResult = {
  readonly card: Card;
  readonly content: string;
  readonly outputPath: string;
  readonly textsWithoutImage: readonly string[];
  readonly imagesWithoutText: readonly string[];
};

// The first line of a generated README. It identifies the card, so that the next run can select a different card.
const headerPattern = /^<!-- Generated by `npm run readme`[^\n]*? Card: (.+?) -->\n/;

export function readmeHeader(card: Card, templatePath: string): string {
  return `<!-- Generated by \`npm run readme\` from ${templatePath}. Do not edit this file. Edit the template. Card: ${card.name} -->\n`;
}

/** Find the card of an earlier generated README. Returns undefined when the file has no valid header. */
export function previousCardName(readme: string | undefined): string | undefined {
  const name = readme === undefined ? undefined : headerPattern.exec(readme)?.[1];
  return name !== undefined && isValidCardName(name) ? name : undefined;
}

/** The date of the reading in the reading time zone, for example `5 November 2026`. */
export function readingDate(now: Date): string {
  return new Intl.DateTimeFormat('en-GB', { timeZone, day: 'numeric', month: 'long', year: 'numeric' }).format(now);
}

/** Make the README text with one random card. This function does not write files. */
export function generateReadme(options: GenerateOptions): GenerateResult {
  const assetsDir = options.assetsDir ?? defaultPaths.assets;
  const templatePath = options.templatePath ?? defaultPaths.template;
  const outputPath = join(options.root, options.outputPath ?? defaultPaths.output);

  const template = readTextFile(join(options.root, templatePath), limits.templateBytes);
  if (template === undefined) throw new GeneratorError(`The template is not found: ${templatePath}`);
  const deck = loadDeck(options.root, assetsDir);
  const previous = previousCardName(readTextFile(outputPath, limits.readmeBytes));
  const card = pickCard(deck.cards, options.random ?? secureRandomIndex, previous);
  const body = renderTemplate(template, card, { date: readingDate(options.now ?? new Date()), cacheKey: options.cacheKey ?? randomBytes(8).toString('hex') });
  const content = `${readmeHeader(card, templatePath)}${body.replace(/\n*$/, '\n')}`;
  return { card, content, outputPath, textsWithoutImage: deck.textsWithoutImage, imagesWithoutText: deck.imagesWithoutText };
}
