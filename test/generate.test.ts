import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { generateReadme, previousCardName, readingDate, readmeHeader } from '@tarot/generate';
import { describe, expect, it } from 'vitest';

import { fixedIndex, makeDefaultRepository, makeRepository } from './helpers';

const now = new Date('2026-11-05T10:00:00Z');

describe('generateReadme', () => {
  it('makes a README with one card, the header, and the template text', () => {
    const root = makeDefaultRepository();
    const result = generateReadme({ root, now, random: fixedIndex(1), cacheKey: 'k' });
    expect(result.card.name).toBe('The Star');
    expect(result.outputPath).toBe(join(root, 'README.md'));
    expect(result.content).toBe(`<!-- Generated by \`npm run readme\` from templates/README.template.md. Do not edit this file. Edit the template. Card: The Star -->
# Top text

Date: 5 November 2026

<img src="assets/The%20Star.png?v=k" alt="The Star">

## The Star

The Star text.

Bottom text
`);
  });

  it('does not write files', () => {
    const root = makeDefaultRepository({ 'README.md': 'old' });
    generateReadme({ root, now, random: fixedIndex(0) });
    expect(readFileSync(join(root, 'README.md'), 'utf8')).toBe('old');
  });

  it('selects a different card than the card in the current README', () => {
    const root = makeDefaultRepository();
    const first = generateReadme({ root, now, random: fixedIndex(0) });
    writeFileSync(first.outputPath, first.content);
    for (let day = 0; day < 5; day += 1) {
      const next = generateReadme({ root, now, random: fixedIndex(0) });
      expect(next.card.name).not.toBe(first.card.name);
    }
  });

  it('fails when the template is missing or not valid', () => {
    const root = makeRepository({ 'assets/The Fool.md': 'Text.', 'assets/The Fool.png': 'png' });
    expect(() => generateReadme({ root, now })).toThrow(/template is not found/);
    writeFileSync(join(root, 'template.md'), '<!-- tarot:text -->');
    expect(() => generateReadme({ root, now, templatePath: 'template.md' })).toThrow(/template is not valid/);
  });

  it('uses custom paths', () => {
    const root = makeRepository({ 'cards/Death.md': 'Death text.', 'cards/Death.png': 'png', 't.md': '<!-- tarot:image -->\n<!-- tarot:text -->' });
    const result = generateReadme({ root, now, assetsDir: 'cards', templatePath: 't.md', outputPath: 'OUT.md', random: fixedIndex(0), cacheKey: 'k' });
    expect(result.outputPath).toBe(join(root, 'OUT.md'));
    expect(result.content).toContain('<img src="cards/Death.png?v=k" alt="Death">\nDeath text.\n');
  });
});

describe('cache key', () => {
  it('adds a new random cache key to the image link on each run', () => {
    const root = makeDefaultRepository();
    const keys = new Set<string>();
    for (let run = 0; run < 3; run += 1) {
      const match = /\.png\?v=([0-9a-f]{16})" alt=/.exec(generateReadme({ root, now, random: fixedIndex(0) }).content);
      expect(match).not.toBeNull();
      keys.add(match?.[1] ?? '');
    }
    expect(keys.size).toBe(3);
  });
});

describe('previousCardName', () => {
  it('reads the card from a generated header', () => {
    const header = readmeHeader({ name: 'The Fool', text: 't', imagePath: 'a.png' }, 'templates/README.template.md');
    expect(previousCardName(`${header}# Text`)).toBe('The Fool');
  });

  it('returns undefined for a missing file, a file without a header, or a card name that is not valid', () => {
    expect(previousCardName(undefined)).toBeUndefined();
    expect(previousCardName('# Hand-written README\n')).toBeUndefined();
    expect(previousCardName('<!-- Generated by `npm run readme` from x. Card: <b> -->\n')).toBeUndefined();
  });
});

describe('readingDate', () => {
  it('uses the Amsterdam date', () => {
    expect(readingDate(new Date('2026-11-05T22:59:59Z'))).toBe('5 November 2026');
    expect(readingDate(new Date('2026-11-05T23:00:00Z'))).toBe('6 November 2026');
    expect(readingDate(new Date('2026-07-01T21:59:59Z'))).toBe('1 July 2026');
    expect(readingDate(new Date('2026-07-01T22:00:00Z'))).toBe('2 July 2026');
  });
});
